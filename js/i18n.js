  let lang = 'ar';
  try {
    const saved = localStorage.getItem('tp_lang');
    if (saved && DICT[saved]) lang = saved;
  } catch (e) {}

  function t(key, vars) {
    const d = DICT[lang] || DICT.ar;
    let s = d[key] !== undefined ? d[key] : (DICT.ar[key] !== undefined ? DICT.ar[key] : key);
    if (Array.isArray(s)) return s;
    if (vars) {
      for (const k in vars) s = String(s).split('{' + k + '}').join(vars[k]);
    }
    return s;
  }

  function applyStatic() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.placeholder = t(el.dataset.i18nPh);
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      el.innerHTML = t(el.dataset.i18nHtml);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.title = t(el.dataset.i18nTitle);
    });
    document.title = t('app_title');
  }

  function setLang(l) {
    if (!DICT[l]) return;
    lang = l;
    try { localStorage.setItem('tp_lang', l); } catch (e) {}
    applyStatic();
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: l } }));
  }

  function init() {
    applyStatic();
  }

  window.I18N = {
    get lang() { return lang; },
    t,
    setLang,
    init,
    applyStatic,
    other: () => (lang === 'ar' ? 'fr' : 'ar'),
    label: () => (lang === 'ar' ? '🌐 FR' : '🌐 عربي'),
  };
